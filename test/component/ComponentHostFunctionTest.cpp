// add(a: u32, b: u32) -> u32
class Add : public Runtime::Component::HostFunction<Add> {
public:
  static constexpr const char *ParamNames[] = {"a", "b"};
  Expect<uint32_t> body(Runtime::Component::CallingFrame &, uint32_t A,
                        uint32_t B) {
    return A + B;
  }
};

// The "host" instance the guest components import.
std::unique_ptr<Runtime::Instance::ComponentInstance> makeHostInstance() {
  auto Host = std::make_unique<Runtime::Instance::ComponentInstance>("host");
  Host->addHostFunc("add", std::make_unique<Add>());
  Host->addHostFunc("repeat", std::make_unique<Repeat>());
  Host->addHostFunc("sleep", std::make_unique<Sleep>());
  return Host;
}

// Load, validate, and instantiate Wasm against the "host" instance.
void loadWithHost(VM::ComponentVM &VM,
                  const Runtime::Instance::ComponentInstance &Host,
                  Span<const uint8_t> Wasm) {
  VM.getStoreManager().registerInstance(&Host);
  ASSERT_TRUE(VM.loadWasm(Wasm));
  ASSERT_TRUE(VM.validate());
  ASSERT_TRUE(VM.instantiate());
}

