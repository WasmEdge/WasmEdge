TEST(ComponentExecutor, EntriesOfOneStoreSerializeAcrossEmbedderThreads) {
  Signals Sig;
  auto Host = newSignalHost(Sig);
  VM::ComponentVM VM(componentConf());
  loadWithHost(VM, *Host, CallsWasm);
  std::atomic<uint32_t> Passed = 0;
  std::vector<std::thread> Embedders;
  for (uint32_t I = 0; I < 4; ++I) {
    Embedders.emplace_back([&VM, &Passed]() {
      for (uint32_t J = 0; J < 8; ++J) {
        if (VM.execute("work")) {
          Passed += 1;
        }
      }
    });
  }
  for (auto &Embedder : Embedders) {
    Embedder.join();
  }
  EXPECT_EQ(Passed.load(), 32u);
  EXPECT_FALSE(Sig.Overlapped);
}

