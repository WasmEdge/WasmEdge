namespace WasmEdge::Runtime::Component {
template <> struct Wit<Colour> : WitEnum<Colour, Wit<Colour>> {
  static constexpr const char *Labels[] = {"red", "green", "blue"};
};
template <> struct Wit<Perms> : WitFlags<Perms, Wit<Perms>> {
  static constexpr const char *Labels[] = {"read", "write", "exec"};
};
template <> struct Wit<Shape> {
  static ComponentValType type(const TypeMinter &Mint) noexcept {
    return WitVariant::type(
        Mint, {{"dot", std::nullopt}, {"circle", Wit<uint32_t>::type(Mint)}});
  }
  static Shape from(const ComponentValVariant &V) {
    const auto &Val = WitVariant::value(V);
    Shape S;
    S.Case = Val.Case;
    if (Val.Case == 1) {
      S.Radius = Wit<uint32_t>::from(*Val.Payload);
    }
    return S;
  }
  static ComponentValVariant into(Shape &&S) noexcept {
    if (S.Case == 1) {
      return WitVariant::into(1, Wit<uint32_t>::into(*S.Radius));
    }
    return WitVariant::into(0);
  }
};
} // namespace WasmEdge::Runtime::Component

