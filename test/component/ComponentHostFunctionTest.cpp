TEST(HostFunction, RunConvertsValues) {
  Runtime::Instance::ComponentInstance Inst("host");
  Runtime::Component::TaskManager Mgr;
  auto *T = Mgr.newTask();
  T->Opts.Inst = &Inst;
  Runtime::Component::CallingFrame Frame(Mgr, *T);
  Repeat F;
  std::vector<ComponentValVariant> Args{ComponentValVariant{uint32_t(2)},
                                        ComponentValVariant{std::string("ab")}};
  std::vector<ComponentValVariant> Rets(1);
  ASSERT_TRUE(F.run(Frame, Args, Rets));
  const auto &Aggregate = std::get<std::shared_ptr<ValComp>>(Rets[0]);
  ASSERT_TRUE(Aggregate);
  const auto &L = std::get<ListVal>(Aggregate->V);
  ASSERT_EQ(L.Elements.size(), 4u);
  EXPECT_EQ(std::get<uint8_t>(L.Elements[0]), uint8_t('a'));
  EXPECT_EQ(std::get<uint8_t>(L.Elements[1]), uint8_t('b'));
  EXPECT_EQ(std::get<uint8_t>(L.Elements[2]), uint8_t('a'));
  EXPECT_EQ(std::get<uint8_t>(L.Elements[3]), uint8_t('b'));
}

TEST(HostFunction, RunRoundTripsRecords) {
  Runtime::Instance::ComponentInstance Inst("host");
  Runtime::Component::TaskManager Mgr;
  auto *T = Mgr.newTask();
  T->Opts.Inst = &Inst;
  Runtime::Component::CallingFrame Frame(Mgr, *T);
  Bump F;
  std::vector<ComponentValVariant> Args{
      Runtime::Component::Wit<Pair>::into(Pair{41, "hi"})};
  std::vector<ComponentValVariant> Rets(1);
  ASSERT_TRUE(F.run(Frame, Args, Rets));
  const auto &Aggregate = std::get<std::shared_ptr<ValComp>>(Rets[0]);
  ASSERT_TRUE(Aggregate);
  const auto &R = std::get<RecordVal>(Aggregate->V);
  ASSERT_EQ(R.Fields.size(), 2u);
  EXPECT_EQ(R.Fields[0].first, "left");
  EXPECT_EQ(std::get<uint32_t>(R.Fields[0].second), 42u);
  EXPECT_EQ(R.Fields[1].first, "right");
  EXPECT_EQ(std::get<std::string>(R.Fields[1].second), "hi!");
}

