TEST(CallingFrame, BlockingRunsTheOperationOnAnotherThread) {
  auto Self = std::make_shared<std::thread::id>();
  auto Seen = std::make_shared<std::thread::id>();
  bool Cancelled = true;
  const auto T0 = Runtime::Component::HostReactor::Clock::now();
  EXPECT_TRUE(runOnTaskThread(
      [&](Runtime::Component::CallingFrame &Frame) -> Expect<void> {
        *Self = std::this_thread::get_id();
        EXPECTED_TRY(Frame.blocking([Seen]() {
          std::this_thread::sleep_for(20ms);
          *Seen = std::this_thread::get_id();
        }));
        Cancelled = Frame.isCancelled();
        return {};
      }));
  EXPECT_GE(Runtime::Component::HostReactor::Clock::now() - T0, 20ms);
  EXPECT_NE(*Seen, *Self);
  EXPECT_FALSE(Cancelled);
}

TEST(CallingFrame, SpawnStartsAtTheSchedulerNextTurn) {
  Runtime::Instance::ComponentInstance Inst("host");
  Configure Conf;
  Executor::Executor Core(Conf);
  Executor::ComponentExecutor Exec(Core);
  auto &Mgr = Exec.getTaskManager();
  auto *T = Mgr.newTask();
  T->Opts.Inst = &Inst;
  T->Opts.Async = true;
  T->IsFuncTypeAsync = true;
  T->Status = Runtime::Component::Task::State::Started;
  Runtime::Component::CallingFrame Frame(Mgr, *T);
  auto Steps = std::make_shared<uint32_t>(0);
  Frame.spawn([Steps](Runtime::Component::CallingFrame &F) -> Expect<void> {
    *Steps = 1;
    EXPECTED_TRY(F.sleepFor(20ms));
    *Steps = 2;
    return {};
  });
  // The task is parked ready; the scheduler starts it.
  EXPECT_EQ(*Steps, 0u);
  EXPECT_TRUE(Mgr.hasParkedThreads());
  const auto T0 = Runtime::Component::HostReactor::Clock::now();
  EXPECT_TRUE(Exec.pumpUntil([Steps]() { return *Steps == 2; }));
  EXPECT_GE(Runtime::Component::HostReactor::Clock::now() - T0, 20ms);
  EXPECT_FALSE(Mgr.getTrapLatch().has_value());
}

