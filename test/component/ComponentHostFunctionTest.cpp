enum class Colour : uint32_t { Red, Green, Blue };
enum class Perms : uint32_t { Read = 1, Write = 2, Exec = 4 };
// variant shape { dot, circle(u32) }
struct Shape {
  uint32_t Case = 0;
  std::optional<uint32_t> Radius;
};
struct CounterTag {};

