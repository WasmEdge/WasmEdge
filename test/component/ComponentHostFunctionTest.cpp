TEST(ComponentCallingFrame, SpawnStartsAtTheSchedulerNextTurn) {
  auto Steps = std::make_shared<uint32_t>(0);
  const auto T0 = std::chrono::steady_clock::now();
  EXPECT_TRUE(runOnCarrier(
      [Steps](Runtime::Component::CallingFrame &Frame) -> Expect<void> {
        Frame.spawn(
            [Steps](Runtime::Component::CallingFrame &Spawned) -> Expect<void> {
              *Steps = 1;
              EXPECTED_TRY(Spawned.sleepFor(20ms));
              *Steps = 2;
              return {};
            });
        // The spawned task starts only once this one cedes the stack.
        EXPECT_EQ(*Steps, 0u);
        EXPECTED_TRY(Frame.waitUntil([Steps]() { return *Steps == 2; }));
        return {};
      }));
  EXPECT_EQ(*Steps, 2u);
  EXPECT_GE(std::chrono::steady_clock::now() - T0, 20ms);
}

