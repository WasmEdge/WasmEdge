// produce() -> stream<u32>: parks one host value for the guest to read.
class ProduceValue : public Runtime::Component::HostFunction<ProduceValue> {
public:
  explicit ProduceValue(ComponentValVariant V) noexcept : Val(std::move(V)) {}
  Expect<Runtime::Component::Stream<uint32_t>>
  body(Runtime::Component::CallingFrame &Frame) {
    const auto Ends = Frame.getExecutor().newHostStream(
        Frame, false, ComponentValType(ComponentTypeCode::U32));
    Runtime::Component::Stream<uint32_t> Out{Ends.second};
    Frame.getExecutor().spawnStreamWrite(Frame, Ends.first, Val);
    return Out;
  }

private:
  ComponentValVariant Val;
};

