TEST(ComponentExecutor, ATrapLeavesTheTasksOfOtherTreesParked) {
  Signals Sig;
  auto Host = newSignalHost(Sig);
  VM::ComponentVM Parking(componentConf());
  loadWithHost(Parking, *Host, ParkWasm);
  VM::ComponentVM Trapping(componentConf());
  loadWithHost(Trapping, *Host, CallsWasm);
  // The task of `park` resolves and stays parked in the host.
  ASSERT_TRUE(Parking.execute("park"));
  EXPECT_FALSE(Trapping.execute("fail"));
  // The trapped tree rejects every entry; the parked task of the other tree
  // wakes and finishes when let go.
  EXPECT_FALSE(Trapping.execute("inner"));
  Sig.Go = true;
  EXPECT_TRUE(Parking.execute("pump"));
  EXPECT_TRUE(Sig.Finished);
}

