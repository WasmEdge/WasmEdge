// Load, validate, and instantiate Wasm against the WASI hosts of VM.
void loadWasi(VM::ComponentVM &VM, Span<const uint8_t> Wasm) {
  ASSERT_TRUE(VM.loadWasm(Wasm));
  ASSERT_TRUE(VM.validate());
  ASSERT_TRUE(VM.instantiate());
}

