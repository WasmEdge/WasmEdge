TEST(ComponentWasi, EnvironmentComesFromTheInitializedEnv) {
  VM::ComponentVM VM(wasiConf());
  ASSERT_NE(VM.getWasiEnv(), nullptr);
  const std::vector<std::string> Args{"x", "yz"};
  const std::vector<std::string> Envs{"A=1", "B=2"};
  VM.getWasiEnv()->init({}, "prog", Args, Envs);
  loadWasi(VM, WasiEnvironmentWasm);
  auto Res = VM.execute("run");
  ASSERT_TRUE(Res);
  ASSERT_EQ(Res->size(), 1u);
  EXPECT_EQ(std::get<uint32_t>((*Res)[0].first), 30421u);
}

TEST(ComponentWasi, VMWithoutWasiHasNoEnv) {
  Configure Conf;
  Conf.addProposal(Proposal::Component);
  VM::ComponentVM VM(Conf);
  EXPECT_EQ(VM.getWasiEnv(), nullptr);
  ASSERT_TRUE(VM.loadWasm(WasiEnvironmentWasm));
  ASSERT_TRUE(VM.validate());
  auto Res = VM.instantiate();
  ASSERT_FALSE(Res);
  EXPECT_EQ(Res.error(), ErrCode::Value::ComponentImportNotFound);
}

