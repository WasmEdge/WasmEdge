    ASSERT_EQ(::write(In[1], Input.data(), Input.size()),
              static_cast<ssize_t>(Input.size()));
    ::close(In[1]);
    loadWasi(VM, WasiStdioWasm);
    std::vector<ComponentValVariant> Params{ComponentValVariant{Chunk}};
    std::vector<ComponentValType> Types{
        ComponentValType(ComponentTypeCode::U32)};
    auto Res = VM.execute("run", Params, Types);
    ASSERT_TRUE(Res) << "chunk " << Chunk;
    ASSERT_EQ(Res->size(), 1u);
