/// One official FIPS 203 known answer test vector per ML-KEM parameter set,
/// taken from the OpenSSL 3.5.7 test data at
/// test/recipes/30-test_evp_data/evppkey_ml_kem_<bits>_{keygen,decap}.txt
/// (test vector 0 of each file, Apache-2.0). The decapsulation vectors use the
/// same key as the key generation vectors, so the decapsulation key is stored
/// once.
struct MlKemKat {
  /// FIPS 203 key generation seed, the concatenation of d and z.
  std::string_view Seed;
  /// Encapsulation key expected from Seed.
  std::string_view PublicKey;
  /// Decapsulation key expected from Seed.
  std::string_view SecretKey;
  /// Ciphertext to decapsulate with SecretKey.
  std::string_view Ciphertext;
  /// Shared secret expected from decapsulating Ciphertext.
  std::string_view Secret;
};

/// Decode a hex vector into bytes.
inline std::vector<uint8_t> mlKemKatBytes(std::string_view Hex) noexcept {
  std::vector<uint8_t> Res;
  Res.reserve(Hex.size() / 2);
  const auto Nibble = [](char C) noexcept -> uint8_t {
    if (C >= '0' && C <= '9') {
      return static_cast<uint8_t>(C - '0');
    }
    return static_cast<uint8_t>(C - 'a' + 10);
  };
  for (size_t I = 0; I + 1 < Hex.size(); I += 2) {
    Res.push_back(
        static_cast<uint8_t>(Nibble(Hex[I]) << 4 | Nibble(Hex[I + 1])));
  }
  return Res;
}

