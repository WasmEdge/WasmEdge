OwnedImage pattern(uint32_t W, uint32_t H, uint32_t C) {
  std::vector<uint8_t> Px(static_cast<size_t>(W) * H * C);
  for (size_t I = 0; I < Px.size(); ++I) {
    Px[I] = static_cast<uint8_t>(I * 37 + 11);
  }
  return std::move(*OwnedImage::copyOf(Px, W, H, C));
}

void appendBytes(void *Context, void *Data, int Size) {
  auto *Out = static_cast<std::vector<uint8_t> *>(Context);
  const auto *Bytes = static_cast<const uint8_t *>(Data);
  Out->insert(Out->end(), Bytes, Bytes + Size);
}

std::vector<uint8_t> samplePixels(int W, int H, int C) {
  std::vector<uint8_t> Px(static_cast<size_t>(W) * H * C);
  for (size_t I = 0; I < Px.size(); ++I) {
    Px[I] = static_cast<uint8_t>(I * 53 + 7);
  }
  return Px;
}

std::vector<uint8_t> makePng(int W, int H, int C) {
  const auto Px = samplePixels(W, H, C);
  std::vector<uint8_t> Out;
  if (stbi_write_png_to_func(appendBytes, &Out, W, H, C, Px.data(), 0) == 0) {
    Out.clear();
  }
  return Out;
}

std::vector<uint8_t> makeTwoChannelPng(int W, int H) {
  return makePng(W, H, 2);
}

