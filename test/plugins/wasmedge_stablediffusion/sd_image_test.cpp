TEST(SDImageTest, PngRoundTripIsPixelExact) {
  const auto Src = pattern(3, 2, 3);
  auto Png = encodePng(Src);
  ASSERT_TRUE(Png);
  const Span<const uint8_t> Bytes(Png->Data.get(), Png->Size);
  auto Head = probeImage(Bytes);
  ASSERT_TRUE(Head);
  EXPECT_EQ(Head->Width, 3U);
  EXPECT_EQ(Head->Height, 2U);
  EXPECT_EQ(Head->Channels, 3U);
  auto Back = decodeImage(Bytes, 3);
  ASSERT_TRUE(Back);
  EXPECT_TRUE(std::equal(Src.pixels().begin(), Src.pixels().end(),
                         Back->pixels().begin(), Back->pixels().end()));
  auto Gray = decodeImage(Bytes, 1);
  ASSERT_TRUE(Gray);
  EXPECT_EQ(Gray->pixels().size(), 6U);
}

