std::vector<uint8_t> makeBmp(int W, int H) {
  const auto Px = samplePixels(W, H, 3);
  std::vector<uint8_t> Out;
  if (stbi_write_bmp_to_func(appendBytes, &Out, W, H, 3, Px.data()) == 0) {
    Out.clear();
  }
  return Out;
}

std::vector<uint8_t> pngOf(const OwnedImage &Image) {
  auto Png = encodePng(Image);
  if (!Png) {
    return {};
  }
  return {Png->Data.get(), Png->Data.get() + Png->Size};
}

void appendBigEndian(std::vector<uint8_t> &Out, uint32_t Value) {
  for (int Shift = 24; Shift >= 0; Shift -= 8) {
    Out.push_back(static_cast<uint8_t>(Value >> Shift));
  }
}

void appendChunk(std::vector<uint8_t> &Out, const char *Type,
                 const std::vector<uint8_t> &Data) {
  appendBigEndian(Out, static_cast<uint32_t>(Data.size()));
  Out.insert(Out.end(), Type, Type + 4);
  Out.insert(Out.end(), Data.begin(), Data.end());
  appendBigEndian(Out, 0);
}

std::vector<uint8_t> makeRawPng(uint32_t W, uint32_t H, uint8_t BitDepth,
                                uint8_t ColorType, uint8_t Interlace,
                                uint32_t InflatedBytes,
                                uint32_t TextBytes = 0) {
  std::vector<uint8_t> Header;
  appendBigEndian(Header, W);
  appendBigEndian(Header, H);
  Header.insert(Header.end(), {BitDepth, ColorType, 0, 0, Interlace});
  std::vector<uint8_t> Zeros(InflatedBytes);
  int Len = 0;
  unsigned char *Deflated =
      stbi_zlib_compress(Zeros.data(), static_cast<int>(Zeros.size()), &Len, 8);
  if (Deflated == nullptr) {
    return {};
  }
  const std::vector<uint8_t> Data(Deflated, Deflated + Len);
  std::free(Deflated);
  std::vector<uint8_t> Out = {0x89, 'P', 'N', 'G', '\r', '\n', 0x1A, '\n'};
  appendChunk(Out, "IHDR", Header);
  if (TextBytes != 0) {
    appendChunk(Out, "tEXt", std::vector<uint8_t>(TextBytes));
  }
  appendChunk(Out, "IDAT", Data);
  appendChunk(Out, "IEND", {});
  return Out;
}

uint32_t adam7Bytes(uint32_t W, uint32_t H, uint32_t BytesPerPixel) {
  constexpr std::array<uint32_t, 7> XStart = {0, 4, 0, 2, 0, 1, 0};
  constexpr std::array<uint32_t, 7> YStart = {0, 0, 4, 0, 2, 0, 1};
  constexpr std::array<uint32_t, 7> XStep = {8, 8, 4, 4, 2, 2, 1};
  constexpr std::array<uint32_t, 7> YStep = {8, 8, 8, 4, 4, 2, 2};
  uint32_t Bytes = 0;
  for (size_t P = 0; P < XStart.size(); ++P) {
    const uint32_t Columns =
        W > XStart[P] ? (W - XStart[P] + XStep[P] - 1) / XStep[P] : 0;
    const uint32_t Rows =
        H > YStart[P] ? (H - YStart[P] + YStep[P] - 1) / YStep[P] : 0;
    if (Columns != 0 && Rows != 0) {
      Bytes += Rows * (1 + Columns * BytesPerPixel);
    }
  }
  return Bytes;
}
